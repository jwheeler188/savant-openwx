#!/usr/bin/env python3
"""
Generates the Savant Blueprint component profile from the bridge's STATE_DEFS,
so the profile's status parsers always match what the bridge sends.

    python3 generate_profile.py            -> writes openwx_weatherbridge.xml

Structure follows Savant's own Weather_controller profiles (Weatherflow Tempest,
Yahoo Weather Client): empty <implementation>, user-editable state variables set
in Inspector, <parameter_list> for command parameters, and execute_on_schedule
to run actions at startup.
"""
import sys
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "bridge"))
from openwx_bridge import STATE_DEFS, VERSION, THRESHOLD_KEYS, DEFAULT_CONFIG  # noqa: E402

LC = "Weather"
import re

MANUFACTURER = "OpenWx"
MODEL = "WeatherBridge"


def profile_filename(manufacturer, model):
    """Blueprint's naming rule, matching its own files: manufacturer + "_" + model, lowercased,
    every character that isn't a-z or 0-9 replaced with "_".
    e.g. TCL / (xx)405 -> tcl__xx_405.xml ; Weatherflow / Tempest -> weatherflow_tempest.xml"""
    return re.sub(r"[^a-z0-9]", "_", f"{manufacturer}_{model}".lower()) + ".xml"


OUT = HERE / profile_filename(MANUFACTURER, MODEL)


# Thresholds editable in Blueprint Inspector. Blank = use the bridge's config.json value.
THRESHOLD_VARS = {
    "wind_protect_gust": ("Threshold Wind Protect Gust", "mph; ACT_WIND_PROTECT = 1 when gust now or in the next 3 h reaches this"),
    "rain_soon_chance": ("Threshold Rain Soon Chance", "%; ACT_RAIN_SOON = 1 when rain chance in the next 3 h reaches this"),
    "rain_expected_chance": ("Threshold Rain Expected Chance", "%; H3/H12/H24_RAIN_EXPECTED = 1 at or above this"),
    "freeze_temp": ("Threshold Freeze Temp", "degrees F; ACT_FREEZE_TONIGHT / *_FREEZE_EXPECTED at or below this"),
    "high_uv": ("Threshold High UV", "UV index; ACT_HIGH_UV = 1 at or above this"),
    "heat_feels": ("Threshold Heat Feels Like", "degrees F; ACT_HEAT = 1 when feels-like reaches this"),
}
# wind_icon_gust is deliberately left out: it only affects the *_ICON values and the web dashboard,
# not any automation, so it stays in the bridge's config.json only.
assert set(THRESHOLD_VARS) <= set(THRESHOLD_KEYS), "profile threshold names out of sync with the bridge"
PROFILE_THRESHOLDS = [k for k in THRESHOLD_KEYS if k in THRESHOLD_VARS]


def threshold_state_vars():
    out = []
    for k in PROFILE_THRESHOLDS:
        name, note = THRESHOLD_VARS[k]
        default = DEFAULT_CONFIG["thresholds"][k]
        out.append(f'        <state_variable name="{name}" state_center_type="string" '
                   f'note="{attr(note)}. Blank = bridge config.json (default {default})" '
                   f'owning_logical_component="{LC}" user_editable="yes" receive_updates_from_state_center="yes"></state_variable>')
    return "\n".join(out)


def send_thresholds_action():
    """One action, one command per threshold: SET <key> <value>. Runs at startup."""
    cmds = "".join(f"""
                    <command response_required="no">
                        <command_string type="character">SET {k} </command_string>
                        <parameter_list>
                            <parameter parameter_data_type="character" state_variable="{THRESHOLD_VARS[k][0]}"/>
                        </parameter_list>
                        <delay ms_delay="50"/>
                    </command>""" for k in PROFILE_THRESHOLDS)
    return f"""
            <!-- Sent at startup and whenever run. Blank values fall back to the bridge's config.json. -->
            <action name="SendThresholds">
                <command_interface interface="ip">{cmds}
                </command_interface>
                <execute_on_schedule period_ms="0"></execute_on_schedule>
            </action>"""


def attr(s):
    return escape(s, {'"': "&quot;"})


HEAD = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Savant OpenWx profile v{VERSION} (MIT License). Generated by generate_profile.py: edit the generator, not this file.
     Not affiliated with or endorsed by Savant Systems, Inc. -->
<component xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="racepoint_component_profile.xsd" manufacturer="{MANUFACTURER}" model="{MODEL}" device_class="Weather_controller" minimum_component_engine_version="0" rpm_xml_version="{VERSION}">
    <notes>

        Savant OpenWx: weather, forecast and NWS watches/warnings from the OpenWx bridge service.
        Manual: MANUAL.pdf in the release package.
        Values update every 5 minutes; only changed values are sent.

        SETUP
        1. Set the Host (IP) Address to the machine running the bridge (usually this Savant host's own IP). Port 2350.
        2. Open the profile in Inspector, select "State Variables":
           - "Site Coordinates": the job site as lat,lon (e.g. 29.7604,-95.3698).
           - "Location Override" (optional): a zip (77494), lat,lon, or City, ST. Takes priority over Site Coordinates.
             Leave blank to use Site Coordinates.
           Both are sent to the bridge automatically when the host starts.
        3. To change the override at runtime: update "Location Override", then run the SendLocationOverride action.
        4. "Contact Email": your company email. NWS, EPA, MET Norway and USNO ask for contact info with every request.
           SYS_CONTACT_SET = 1 once a real address is set (here or in the bridge's config.json).
        5. Optional "Open-Meteo API Key": with a key the forecast comes from Open-Meteo's commercial service;
           the word private uses Open-Meteo's free service (personal/office testing only, not client installs);
           blank uses the free National Weather Service forecast + EPA UV (US only). SYS_FORECAST_SOURCE shows which.
        6. Optional thresholds for the ACT_ flags: the "Threshold ..." state variables (blank = the bridge's config.json value).
           Sent at startup; after changing one at runtime, run the SendThresholds action.
           TH_* states show the thresholds the bridge is actually using.

        Location priority on the bridge: Location Override, then Site Coordinates, then default_location in its config.json.
        All weather states are listed in STATES.md. Gate weather automations on SYS_ONLINE = 1.

    </notes>
    <control_interfaces preferred="ip">
        <ip port="2350" response_time_length_ms="1000">
            <send_postfix type="hex">0A</send_postfix>
            <receive_end_condition test_condition="data" type="hex">0A</receive_end_condition>
        </ip>
    </control_interfaces>
    <media_interfaces>
        <data name_on_component="Ethernet">
            <combined_media>
                <data_media type="ethernet"/>
                <control port="2350"/>
            </combined_media>
        </data>
    </media_interfaces>
    <state_variable_list>
        <state_variable name="Site Coordinates" state_center_type="string" note="Job site latitude,longitude, e.g. 29.7604,-95.3698" owning_logical_component="{LC}" user_editable="yes"></state_variable>
        <state_variable name="Location Override" state_center_type="string" note="Optional: zip, lat,lon, or City, ST. Blank = use Site Coordinates" owning_logical_component="{LC}" user_editable="yes" receive_updates_from_state_center="yes"></state_variable>
        <state_variable name="Contact Email" state_center_type="string" note="Your company email, sent to NWS/EPA/MET Norway/USNO as their terms ask. Blank = contact_email in the bridge's config.json" owning_logical_component="{LC}" user_editable="yes" receive_updates_from_state_center="yes"></state_variable>
        <state_variable name="Open-Meteo API Key" state_center_type="string" note="Optional. Your key: Open-Meteo commercial forecast. private: free Open-Meteo for personal/office testing only (non-commercial). Blank: free NWS forecast + EPA UV (US only)" owning_logical_component="{LC}" user_editable="yes" receive_updates_from_state_center="yes"></state_variable>
__THRESHOLD_VARS__
    </state_variable_list>
"""


def status_messages():
    # Each bridge line is KEY=value<LF>. receive_end_condition splits on LF;
    # match the literal "KEY=" and take the rest of the line as the value.
    out = ["        <status_messages>"]
    for key, typ, desc in STATE_DEFS:
        out.append(f"""            <status_message name="{key}">
                <constant type="character">{key}=</constant>
                <data type="character" terminator_type="end_of_data">
                    <update state="{key}" type="{typ}"/>
                </data>
            </status_message>""")
    out.append("        </status_messages>")
    return "\n".join(out)


def action(name, cmd, state_var=None, schedules=(), comment=""):
    params = ""
    if state_var:
        params = f"""
                        <parameter_list>
                            <parameter parameter_data_type="character" state_variable="{state_var}"/>
                        </parameter_list>"""
    cmd_text = cmd  # send_postfix adds the LF
    sched = "".join(f'\n                <execute_on_schedule period_ms="{ms}"></execute_on_schedule>' for ms in schedules)
    c = f"\n            <!-- {comment} -->" if comment else ""
    return f"""{c}
            <action name="{name}">
                <command_interface interface="ip">
                    <command response_required="no">
                        <command_string type="character">{cmd_text}</command_string>{params}
                    </command>
                </command_interface>{sched}
            </action>"""


def actions():
    acts = [
        action("SendSiteCoordinates", "SITE ", "Site Coordinates", (0,),
               "Sent at startup. Ignored by the bridge if blank or 0,0."),
        action("SendLocationOverride", "OVERRIDE ", "Location Override", (0,),
               "Sent at startup and whenever run. Blank clears the override."),
        action("SendContactEmail", "CONTACT ", "Contact Email", (0,),
               "Sent at startup and whenever run. Blank = config.json contact_email."),
        action("SendApiKey", "APIKEY ", "Open-Meteo API Key", (0,),
               "Sent at startup and whenever run. Blank = free NWS forecast."),
        send_thresholds_action(),
        action("ClearLocationOverride", "OVERRIDE CLEAR", comment="Return to Site Coordinates / default."),
        action("RefreshWeather", "REFRESH", comment="Fetch weather now."),
        action("RequestAllStates", "DUMP", comment="Resend every state."),
        action("Ping", "PING", schedules=(60000,), comment="Keepalive every minute; the bridge answers PONG."),
    ]
    return "        <custom_component_actions>" + "".join(acts) + "\n        </custom_component_actions>"


def build_minimal():
    """Tiny profile (3 states, 2 actions) to tell a structure problem from a content problem."""
    keep = {"SYS_ONLINE", "CUR_TEMP", "CUR_SUMMARY"}
    global STATE_DEFS
    full = STATE_DEFS
    STATE_DEFS = [d for d in full if d[0] in keep]
    test_model = MODEL + "Test"
    head = HEAD.replace(f'model="{MODEL}"', f'model="{test_model}"').replace("__THRESHOLD_VARS__\n", "")
    body = [head, f'    <logical_component logical_component_name="{LC}">', "        <implementation></implementation>",
            status_messages(),
            "        <custom_component_actions>" + action("Ping", "PING") + action("RefreshWeather", "REFRESH")
            + "\n        </custom_component_actions>",
            "    </logical_component>", "</component>", ""]
    STATE_DEFS = full
    out = HERE / profile_filename(MANUFACTURER, test_model)
    out.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {out.name}: 3 status parsers")


def build():
    body = [
        HEAD.replace("__THRESHOLD_VARS__", threshold_state_vars()),
        f'    <logical_component logical_component_name="{LC}">',
        "        <implementation></implementation>",
        status_messages(),
        actions(),
        "    </logical_component>",
        "</component>",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(STATE_DEFS)} status parsers")


if __name__ == "__main__":
    build()
    if "--test" in sys.argv:  # optional 3-state profile for diagnosing import problems
        build_minimal()
